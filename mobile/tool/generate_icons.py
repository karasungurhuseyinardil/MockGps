"""Generates the Mock GPS app icon for Android and iOS from one geometry.

Design: blue gradient background (brand primary), white location pin, coral dot in the pin
(coral = "simulated location" in the design system) and a soft ring under the tip.

Usage (from mobile/):  python tool/generate_icons.py
Requires Pillow.
"""
import json
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "android/app/src/main/res"
IOS = ROOT / "ios/Runner/Assets.xcassets/AppIcon.appiconset"
BRAND = ROOT / "assets/brand"

TOP = (0x4A, 0x6C, 0xFF)      # gradient start
BOTTOM = (0x24, 0x3F, 0xD6)   # gradient end
PRIMARY = "#3457F5"
CORAL = (0xF2, 0x54, 0x2D)
WHITE = (255, 255, 255)

# Geometry in a 108×108 box (Android adaptive icon units). Safe zone is the centred 66×66 circle.
CX, CY, R = 54.0, 47.0, 17.0   # pin head circle
TIP_Y = 77.0                  # pin tip
DOT_R = 7.0                   # coral dot
RING = (54.0, 79.0, 13.0, 3.6)  # ellipse centre x, y, rx, ry


def tangent_points():
    """Points where straight lines from the tip touch the head circle."""
    d = TIP_Y - CY
    angle = math.asin(R / d)              # angle between tip→centre line and tangent
    t = math.sqrt(d * d - R * R)          # tangent length
    # Tangent points measured from the tip, rotated ±angle off the vertical.
    lx = CX - t * math.sin(angle)
    ly = TIP_Y - t * math.cos(angle)
    rx = CX + t * math.sin(angle)
    return (lx, ly), (rx, ly)


def pin_polygon(scale: float, steps: int = 180):
    (lx, ly), (rx, ry) = tangent_points()
    start = math.atan2(ly - CY, lx - CX)
    end = math.atan2(ry - CY, rx - CX)
    # Go the long way, over the top of the circle (increasing angle with y pointing down).
    if end < start:
        end += 2 * math.pi
    pts = [(CX * scale, TIP_Y * scale)]
    for i in range(steps + 1):
        a = start + (end - start) * i / steps
        pts.append(((CX + R * math.cos(a)) * scale, (CY + R * math.sin(a)) * scale))
    return pts


def render(size: int, *, background=True, full_bleed=True, foreground_scale=1.0) -> Image.Image:
    """Renders at 4× and downsamples for smooth edges."""
    ss = size * 4
    img = Image.new("RGBA", (ss, ss), (0, 0, 0, 0))
    if background:
        grad = Image.new("RGB", (1, ss))
        for y in range(ss):
            t = y / (ss - 1)
            grad.putpixel((0, y), tuple(int(TOP[i] + (BOTTOM[i] - TOP[i]) * t) for i in range(3)))
        img.paste(grad.resize((ss, ss)), (0, 0))

    # Map the 108-unit design box onto the canvas. Legacy/iOS icons show the whole box.
    unit = ss / 108.0 * foreground_scale
    offset = (ss - 108.0 * unit) / 2

    layer = Image.new("RGBA", (ss, ss), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    ex, ey, erx, ery = RING
    d.ellipse([offset + (ex - erx) * unit, offset + (ey - ery) * unit, offset + (ex + erx) * unit, offset + (ey + ery) * unit],
              fill=(255, 255, 255, 90))
    poly = [(offset + x, offset + y) for x, y in pin_polygon(unit)]

    shadow = Image.new("RGBA", (ss, ss), (0, 0, 0, 0))
    ImageDraw.Draw(shadow).polygon([(x, y + 1.5 * unit) for x, y in poly], fill=(10, 20, 80, 110))
    shadow = shadow.filter(ImageFilter.GaussianBlur(2.2 * unit))
    layer = Image.alpha_composite(shadow, layer)
    d = ImageDraw.Draw(layer)
    d.polygon(poly, fill=WHITE)
    d.ellipse([offset + (CX - DOT_R) * unit, offset + (CY - DOT_R) * unit, offset + (CX + DOT_R) * unit, offset + (CY + DOT_R) * unit],
              fill=CORAL)

    img = Image.alpha_composite(img, layer)
    img = img.resize((size, size), Image.LANCZOS)
    if full_bleed and background:
        img = img.convert("RGB")
    return img


def vector_path() -> str:
    (lx, ly), (rx, ry) = tangent_points()
    f = lambda v: f"{v:.3f}"
    return f"M{f(CX)},{f(TIP_Y)} L{f(lx)},{f(ly)} A{f(R)},{f(R)} 0 1,1 {f(rx)},{f(ry)} Z"


def circle_path(cx, cy, r) -> str:
    return f"M{cx - r:.3f},{cy:.3f} a{r:.3f},{r:.3f} 0 1,0 {2 * r:.3f},0 a{r:.3f},{r:.3f} 0 1,0 {-2 * r:.3f},0 Z"


def write_android():
    # Adaptive icon (API 26+ — the app's minSdk, so this covers every supported device).
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    ex, ey, erx, ery = RING
    ring = f"M{ex - erx:.3f},{ey:.3f} a{erx:.3f},{ery:.3f} 0 1,0 {2 * erx:.3f},0 a{erx:.3f},{ery:.3f} 0 1,0 {-2 * erx:.3f},0 Z"
    (RES / "drawable/ic_launcher_foreground.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#5AFFFFFF" android:pathData="{ring}" />
    <path android:fillColor="#FFFFFFFF" android:pathData="{vector_path()}" />
    <path android:fillColor="#FFF2542D" android:pathData="{circle_path(CX, CY, DOT_R)}" />
</vector>
""", encoding="utf-8")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. Android 13+ themed icon (single colour). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#FF000000" android:fillType="evenOdd"
        android:pathData="{vector_path()} {circle_path(CX, CY, DOT_R)}" />
</vector>
""", encoding="utf-8")
    (RES / "drawable/ic_launcher_background.xml").write_text("""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="54" android:startY="0" android:endX="54" android:endY="108"
                android:startColor="#FF4A6CFF" android:endColor="#FF243FD6" />
        </aapt:attr>
    </path>
</vector>
""", encoding="utf-8")
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""
    (anydpi / "ic_launcher.xml").write_text(adaptive, encoding="utf-8")
    (anydpi / "ic_launcher_round.xml").write_text(adaptive, encoding="utf-8")

    # PNG fallbacks (also used by some launchers/stores): replace the Flutter logo.
    for folder, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        icon = render(px, foreground_scale=1.25)
        mask = Image.new("L", (px * 4, px * 4), 0)
        ImageDraw.Draw(mask).rounded_rectangle([0, 0, px * 4 - 1, px * 4 - 1], radius=px * 0.9, fill=255)
        rounded = icon.convert("RGBA")
        rounded.putalpha(mask.resize((px, px), Image.LANCZOS))
        rounded.save(RES / f"mipmap-{folder}/ic_launcher.png")
        circle = icon.convert("RGBA")
        cmask = Image.new("L", (px * 4, px * 4), 0)
        ImageDraw.Draw(cmask).ellipse([0, 0, px * 4 - 1, px * 4 - 1], fill=255)
        circle.putalpha(cmask.resize((px, px), Image.LANCZOS))
        circle.save(RES / f"mipmap-{folder}/ic_launcher_round.png")


def write_ios():
    contents = json.loads((IOS / "Contents.json").read_text(encoding="utf-8"))
    for image in contents["images"]:
        name = image.get("filename")
        if not name:
            continue
        points = float(image["size"].split("x")[0])
        scale = int(image["scale"].rstrip("x"))
        px = round(points * scale)
        # iOS applies its own mask; icons must be opaque full squares.
        render(px, foreground_scale=1.3).save(IOS / name)


def write_brand():
    BRAND.mkdir(parents=True, exist_ok=True)
    render(1024, foreground_scale=1.3).save(BRAND / "icon-1024.png")
    render(512, background=False, full_bleed=False, foreground_scale=1.3).save(BRAND / "pin-512.png")


if __name__ == "__main__":
    write_android()
    write_ios()
    write_brand()
    print("Icons written: Android adaptive + PNG, iOS AppIcon set, assets/brand")
